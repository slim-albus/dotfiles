[CmdletBinding()]
param(
    [switch]$DryRun,
    [switch]$TrackWsl,
    [switch]$Force,
    [string]$LogFile
)

$ErrorActionPreference = 'Stop'

if ($LogFile) {
    $logDir = Split-Path -Path $LogFile -Parent
    if ($logDir -and -not (Test-Path -LiteralPath $logDir)) {
        New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    }
    Start-Transcript -Path $LogFile -Append | Out-Null
}

$DotfilesRoot = Split-Path -Parent $PSScriptRoot
$ProfileTarget = $PROFILE.CurrentUserCurrentHost
$GitConfigPath = Join-Path $DotfilesRoot 'shared\git\config'
$GitIgnorePath = Join-Path $DotfilesRoot 'shared\git\ignore'
$WslConfigSource = Join-Path $DotfilesRoot 'wsl\.wslconfig'
$WslConfigTarget = Join-Path $HOME '.wslconfig'

function Write-StepHeader {
    param([string]$Title)
    Write-Host "`n=== $Title ===" -ForegroundColor Cyan
}

function Write-Status {
    param(
        [Parameter(Mandatory)][ValidateSet('OK', 'SKIP', 'WARN', 'FAIL', 'INFO', 'DRY-RUN')]
        [string]$Status,
        [Parameter(Mandatory)][string]$Message
    )
    $color = switch ($Status) {
        'OK'      { 'Green' }
        'SKIP'    { 'Cyan' }
        'WARN'    { 'Yellow' }
        'FAIL'    { 'Red' }
        'INFO'    { 'DarkCyan' }
        'DRY-RUN' { 'Magenta' }
    }
    $badge = "[{0,4}]" -f $Status
    Write-Host "  $badge " -ForegroundColor $color -NoNewline
    Write-Host $Message -ForegroundColor White
}

try {
    Write-Host "`n  ========================================================" -ForegroundColor Cyan
    Write-Host "                Dotfiles Windows Installer                " -ForegroundColor Cyan
    Write-Host "  ========================================================" -ForegroundColor Cyan
    Write-Host "  Source: $DotfilesRoot" -ForegroundColor DarkGray
    Write-Host "  Target: $ProfileTarget" -ForegroundColor DarkGray
    if ($DryRun) {
        Write-Host "  Mode  : PREVIEW ONLY (-DryRun)" -ForegroundColor Magenta
    }

    # ------------------------------------------------------------
    # Step 1: PowerShell Profile Setup (Single-source Loader)
    # ------------------------------------------------------------
    Write-StepHeader "Step [1/4]: Configuring PowerShell Profile"

    $profileDir = Split-Path -Parent $ProfileTarget
    if (-not (Test-Path -LiteralPath $profileDir)) {
        if ($DryRun) {
            Write-Status -Status 'DRY-RUN' -Message "Create profile directory: $profileDir"
        } else {
            New-Item -ItemType Directory -Path $profileDir -Force | Out-Null
            Write-Status -Status 'OK' -Message "Created profile directory: $profileDir"
        }
    }

    $repoProfilePath = Join-Path $DotfilesRoot 'windows\Microsoft.PowerShell_profile.ps1'
    $loaderContent = @"
# ============================================================
# Dotfiles Profile Loader
# Generated by: .\windows\install.ps1
# ============================================================
`$DotfilesProfile = "$repoProfilePath"
if (Test-Path -LiteralPath `$DotfilesProfile) {
    . `$DotfilesProfile
} else {
    Write-Warning "Dotfiles profile not found at '`$DotfilesProfile'."
}
"@

    $needsInstall = $true
    if (Test-Path -LiteralPath $ProfileTarget) {
        $existingContent = Get-Content -LiteralPath $ProfileTarget -Raw -ErrorAction SilentlyContinue
        if ($existingContent -and $existingContent.Contains($repoProfilePath) -and -not $Force) {
            Write-Status -Status 'SKIP' -Message "Profile loader is already configured at: $ProfileTarget"
            $needsInstall = $false
        } else {
            # Backup existing profile
            $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
            $backupPath = "$ProfileTarget.ctt-backup.$timestamp"
            if ($DryRun) {
                Write-Status -Status 'DRY-RUN' -Message "Backup existing profile to: $backupPath"
            } else {
                Copy-Item -LiteralPath $ProfileTarget -Destination $backupPath -Force
                Write-Status -Status 'INFO' -Message "Saved backup of existing profile to: $backupPath"
            }
        }
    }

    if ($needsInstall) {
        if ($DryRun) {
            Write-Status -Status 'DRY-RUN' -Message "Write profile loader pointing to: $repoProfilePath"
        } else {
            Set-Content -LiteralPath $ProfileTarget -Value $loaderContent -Encoding utf8
            Write-Status -Status 'OK' -Message "Installed dotfiles profile loader at: $ProfileTarget"
        }
    }

    # ------------------------------------------------------------
    # Step 2: Shared Git Configuration
    # ------------------------------------------------------------
    Write-StepHeader "Step [2/4]: Configuring Shared Git Settings"

    if (Get-Command git.exe -ErrorAction SilentlyContinue) {
        # Git include.path
        $gitInclude = git config --global --get-all include.path 2>$null
        $formattedGitConfig = $GitConfigPath -replace '\\', '/'
        if ($gitInclude -and ($gitInclude -contains $GitConfigPath -or $gitInclude -contains $formattedGitConfig) -and -not $Force) {
            Write-Status -Status 'SKIP' -Message "Git shared config already included: $GitConfigPath"
        } else {
            if ($DryRun) {
                Write-Status -Status 'DRY-RUN' -Message "git config --global --add include.path `"$GitConfigPath`""
            } else {
                git config --global --add include.path $GitConfigPath
                Write-Status -Status 'OK' -Message "Included shared Git config: $GitConfigPath"
            }
        }

        # Git core.excludesFile
        $currentExclude = git config --global --get core.excludesFile 2>$null
        $formattedGitIgnore = $GitIgnorePath -replace '\\', '/'
        if ($currentExclude -and ($currentExclude -eq $GitIgnorePath -or $currentExclude -eq $formattedGitIgnore) -and -not $Force) {
            Write-Status -Status 'SKIP' -Message "Git global ignore already set: $GitIgnorePath"
        } else {
            if ($DryRun) {
                Write-Status -Status 'DRY-RUN' -Message "git config --global core.excludesFile `"$GitIgnorePath`""
            } else {
                git config --global core.excludesFile $GitIgnorePath
                Write-Status -Status 'OK' -Message "Configured global Git ignore: $GitIgnorePath"
            }
        }
    } else {
        Write-Status -Status 'WARN' -Message "Git not detected in PATH; skipping Git configuration"
    }

    # ------------------------------------------------------------
    # Step 3: WSL Configuration Sync
    # ------------------------------------------------------------
    Write-StepHeader "Step [3/4]: WSL Configuration"

    if (Test-Path -LiteralPath $WslConfigSource) {
        if (-not (Test-Path -LiteralPath $WslConfigTarget)) {
            if ($DryRun) {
                Write-Status -Status 'DRY-RUN' -Message "Copy $WslConfigSource to $WslConfigTarget"
            } else {
                Copy-Item -LiteralPath $WslConfigSource -Destination $WslConfigTarget
                Write-Status -Status 'OK' -Message "Installed WSL configuration to $WslConfigTarget"
            }
        } else {
            $srcHash = (Get-FileHash -LiteralPath $WslConfigSource).Hash
            $tgtHash = (Get-FileHash -LiteralPath $WslConfigTarget).Hash
            if ($srcHash -eq $tgtHash) {
                Write-Status -Status 'SKIP' -Message "WSL config ($WslConfigTarget) is already in sync"
            } else {
                if ($TrackWsl -or $Force) {
                    $wslBackup = "$WslConfigTarget.bak.$(Get-Date -Format yyyyMMdd-HHmmss)"
                    if ($DryRun) {
                        Write-Status -Status 'DRY-RUN' -Message "Backup and overwrite $WslConfigTarget"
                    } else {
                        Copy-Item -LiteralPath $WslConfigTarget -Destination $wslBackup -Force
                        Copy-Item -LiteralPath $WslConfigSource -Destination $WslConfigTarget -Force
                        Write-Status -Status 'OK' -Message "Updated $WslConfigTarget (Backup saved to $wslBackup)"
                    }
                } else {
                    Write-Status -Status 'INFO' -Message "WSL config exists at $WslConfigTarget (use -TrackWsl or -Force to overwrite)"
                }
            }
        }
    } else {
        Write-Status -Status 'SKIP' -Message "No repository wsl/.wslconfig file found"
    }

    # ------------------------------------------------------------
    # Step 4: Verification & Doctor
    # ------------------------------------------------------------
    Write-StepHeader "Step [4/4]: Verification"

    if (-not $DryRun) {
        $doctorScript = Join-Path $DotfilesRoot 'windows\functions.ps1'
        if (Test-Path -LiteralPath $doctorScript) {
            . $doctorScript
            Invoke-DotfilesDoctor
        }
    } else {
        Write-Status -Status 'DRY-RUN' -Message "Doctor verification skipped in dry-run mode"
    }

    Write-Host "`n  ========================================================" -ForegroundColor Green
    Write-Host "           Dotfiles Setup Completed Successfully!         " -ForegroundColor Green
    Write-Host "  ========================================================" -ForegroundColor Green
    Write-Host "  Next steps:" -ForegroundColor DarkGray
    Write-Host "    1. Restart your terminal or run: reload" -ForegroundColor White
    Write-Host "    2. Run 'dots' anytime to explore aliases & commands" -ForegroundColor White
    Write-Host "    3. Run 'dots doctor' to verify system health`n" -ForegroundColor White

} catch {
    Write-Host "`n  [FAIL] Installation encountered an error:" -ForegroundColor Red
    Write-Error $_
} finally {
    if ($LogFile) {
        Stop-Transcript | Out-Null
    }
}